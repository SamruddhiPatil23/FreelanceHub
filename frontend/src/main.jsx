// main.jsx
// Purpose: the actual entry point Vite loads. Wraps App with Redux's Provider
// and React Router's BrowserRouter so every component can use useSelector/
// useDispatch and <Link>/routing.

import React from "react";
import ReactDOM from "react-dom/client";
import { Provider } from "react-redux";
import { BrowserRouter } from "react-router-dom";

import { store } from "./app/store";
import App from "./App";
import "./index.css";

ReactDOM.createRoot(document.getElementById("root")).render(
  <React.StrictMode>
    <Provider store={store}>
      <BrowserRouter>
        <App />
      </BrowserRouter>
    </Provider>
  </React.StrictMode>
);
